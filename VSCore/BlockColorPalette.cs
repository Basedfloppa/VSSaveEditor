using System;

namespace VSCore;

/// <summary>
/// Mapping of a block NAME (a blocktype code from the registry) -> colour and semantics.
/// The code comes from <see cref="BlockRegistry"/> (block id -> code).
///
/// The colours are semantic ("as in the game") and follow the material name in the code:
/// water, ice/snow, foliage/grass, sand, gravel, stone/ore, soil, wood, lava…
/// For an unknown code (mod blocks, chiseled, microblocks) there is a stable fallback
/// keyed by the code STRING: muted, yet light enough tones so that the block does not look black.
/// </summary>
public static class BlockColorPalette
{
    /// <summary>True if the code is water (by the registry blocktype name).
    /// Covers fresh and salt water: water-*, saltwater-*, as well as the bare "water"/"saltwater".
    /// Careful: it does not catch wateringcan/watershed (they have no hyphen after "water").</summary>
    public static bool IsWater(string? code)
    {
        if (string.IsNullOrEmpty(code)) return false;
        var c = code.ToLowerInvariant();
        if (c == "water" || c == "saltwater") return true;
        return c.StartsWith("water-", StringComparison.Ordinal)
            || c.StartsWith("saltwater-", StringComparison.Ordinal);
    }

    /// <summary>
    /// Whether the code name looks like a plant. Needed only as a fallback for MOD blocks that are absent
    /// from the asset table: their `rainPermeable` is unknown, and plants are invisible on the in-game map
    /// (the game colours the first impermeable block). Without this, mod flowers/grass would stay
    /// the top block and be drawn as green dots over the turf.
    /// </summary>
    public static bool IsLikelyPlant(string? code)
    {
        if (string.IsNullOrEmpty(code)) return false;
        var c = code.ToLowerInvariant();
        foreach (var k in PlantKeywords)
            if (c.Contains(k, StringComparison.Ordinal)) return true;
        return false;
    }

    private static readonly string[] PlantKeywords =
    {
        "plant", "grass", "fern", "flower", "bush", "vine", "reed", "cattail", "lily",
        "moss", "mushroom", "sapling", "herb", "thorn", "seaweed", "algae", "kelp",
        "clover", "bloom", "crop", "shrub", "berry",
    };

    /// <summary>True if the code is a chiselled block (Chisel/MicroBlock). For such blocks the actual
    /// material lives in the block entity (see <see cref="ChiselMaterials"/>), while the id itself is shared.</summary>
    public static bool IsChiseled(string? code)
    {
        if (string.IsNullOrEmpty(code)) return false;
        return code.Contains("chisel", StringComparison.OrdinalIgnoreCase)
            || code.Contains("microblock", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>True if the block colour in the game comes from a shader (climate/season/water) rather than a texture:
    /// such blocks have an almost white or utility texture, so the asset table
    /// (<see cref="BlockColors"/>) is not applied to them — we colour them semantically.</summary>
    public static bool IsShaderTinted(string? code)
    {
        if (string.IsNullOrEmpty(code)) return false;
        var c = code.ToLowerInvariant();
        if (IsWater(c) || c.Contains("lava", StringComparison.Ordinal) || c.Contains("magma", StringComparison.Ordinal))
            return true;
        foreach (var k in TintedKeywords)
            if (c.Contains(k, StringComparison.Ordinal)) return true;
        return false;
    }

    private static readonly string[] TintedKeywords =
    {
        "leaves", "leaf", "grass", "fern", "moss", "flower", "bush", "vine", "plant", "reed",
        "cattail", "lily", "crop", "fruit", "berry", "mushroom", "sapling", "herb", "thorn",
        "bamboo", "cactus", "seaweed", "algae", "kelp", "clover", "root", "stem", "bloom",
    };

    /// <summary>Colour for a block code: first the REAL texture colour from the game assets
    /// (<see cref="BlockColors"/>), then the semantics by name, then the stable hash.</summary>
    public static (byte r, byte g, byte b) ColorFor(string? code, ushort id)
    {
        if (string.IsNullOrEmpty(code)) return Fallback("", id);
        var c = code.ToLowerInvariant();

        // Shader-tinted blocks (water/lava/vegetation) have no colour in the asset table
        if (IsShaderTinted(c)) return Semantic(c, id);
        // The real colour of the block from its texture (the table is generated by tools/gen_block_colors.py).
        // We pass the code already lowercased: the hot path must not allocate.
        if (BlockColors.TryGet(c, out var real)) return real;
        // Mod/unknown codes — the semantic rules and the stable fallback
        return Semantic(c, id);
    }

    /// <summary>Semantic colour by block name (the fallback when there is no real colour).</summary>
    private static (byte r, byte g, byte b) Semantic(string c, ushort id)
    {
        // Water/liquids
        if (IsWater(c)) return (38, 105, 190);
        if (c.Contains("lava", StringComparison.Ordinal) || c.Contains("magma", StringComparison.Ordinal)) return (205, 70, 26);

        // Natural surfaces
        if (c.Contains("ice", StringComparison.Ordinal) || c.Contains("snow", StringComparison.Ordinal)) return (215, 228, 238);
        if (c.Contains("leaves", StringComparison.Ordinal) || c.Contains("bush", StringComparison.Ordinal)) return (68, 108, 52);
        if (c.Contains("tallgrass", StringComparison.Ordinal) || c.Contains("grass", StringComparison.Ordinal)
            || c.Contains("fern", StringComparison.Ordinal) || c.Contains("moss", StringComparison.Ordinal)
            || c.Contains("vine", StringComparison.Ordinal)) return (96, 138, 58);
        if (c.Contains("flower", StringComparison.Ordinal) || c.Contains("bloom", StringComparison.Ordinal)
            || c.Contains("crop", StringComparison.Ordinal) || c.Contains("farmland", StringComparison.Ordinal)) return (150, 165, 80);
        if (c.Contains("sand", StringComparison.Ordinal)) return (201, 178, 120);
        if (c.Contains("gravel", StringComparison.Ordinal)) return (142, 136, 128);
        if (c.Contains("soil", StringComparison.Ordinal) || c.Contains("peat", StringComparison.Ordinal)
            || c.Contains("mud", StringComparison.Ordinal) || c.Contains("silt", StringComparison.Ordinal)
            || c.Contains("loam", StringComparison.Ordinal)) return (120, 82, 54);

        // Stones (specific rock types first, then the generic "rock/stone/ore")
        if (c.Contains("marble", StringComparison.Ordinal)) return (225, 224, 218);
        if (c.Contains("limestone", StringComparison.Ordinal) || c.Contains("chalk", StringComparison.Ordinal)) return (203, 198, 178);
        if (c.Contains("sandstone", StringComparison.Ordinal)) return (205, 185, 140);
        if (c.Contains("slate", StringComparison.Ordinal) || c.Contains("shale", StringComparison.Ordinal)
            || c.Contains("conglomerate", StringComparison.Ordinal)) return (104, 106, 112);
        if (c.Contains("basalt", StringComparison.Ordinal)) return (110, 108, 112);
        if (c.Contains("granite", StringComparison.Ordinal)) return (150, 132, 122);
        if (c.Contains("obsidian", StringComparison.Ordinal)) return (72, 66, 84);
        if (c.Contains("quartz", StringComparison.Ordinal)) return (226, 226, 232);
        if (c.Contains("bauxite", StringComparison.Ordinal)) return (170, 140, 125);
        if (c.Contains("rock", StringComparison.Ordinal) || c.Contains("stone", StringComparison.Ordinal)
            || c.Contains("ore", StringComparison.Ordinal)) return (127, 123, 118);

        // Plant/animal materials
        if (c.Contains("wood", StringComparison.Ordinal) || c.Contains("log", StringComparison.Ordinal)
            || c.Contains("plank", StringComparison.Ordinal) || c.Contains("bark", StringComparison.Ordinal)
            || c.Contains("timber", StringComparison.Ordinal)) return (121, 85, 48);
        if (c.Contains("thatch", StringComparison.Ordinal) || c.Contains("straw", StringComparison.Ordinal)
            || c.Contains("hay", StringComparison.Ordinal)) return (188, 162, 92);
        if (c.Contains("cloth", StringComparison.Ordinal) || c.Contains("wool", StringComparison.Ordinal)
            || c.Contains("linen", StringComparison.Ordinal) || c.Contains("carpet", StringComparison.Ordinal)) return (168, 140, 128);
        if (c.Contains("leather", StringComparison.Ordinal) || c.Contains("hide", StringComparison.Ordinal)) return (140, 96, 62);
        if (c.Contains("bone", StringComparison.Ordinal)) return (222, 215, 195);
        if (c.Contains("paper", StringComparison.Ordinal) || c.Contains("parchment", StringComparison.Ordinal)) return (212, 202, 176);

        // Metals and building materials
        if (c.Contains("copper", StringComparison.Ordinal)) return (184, 115, 71);
        if (c.Contains("gold", StringComparison.Ordinal)) return (212, 175, 55);
        if (c.Contains("silver", StringComparison.Ordinal)) return (192, 192, 200);
        if (c.Contains("metal", StringComparison.Ordinal) || c.Contains("iron", StringComparison.Ordinal)
            || c.Contains("steel", StringComparison.Ordinal) || c.Contains("meteoric", StringComparison.Ordinal)) return (140, 142, 148);
        if (c.Contains("clay", StringComparison.Ordinal)) return (166, 120, 96);
        if (c.Contains("brick", StringComparison.Ordinal) || c.Contains("mortar", StringComparison.Ordinal)
            || c.Contains("plaster", StringComparison.Ordinal)) return (150, 92, 72);
        if (c.Contains("glass", StringComparison.Ordinal)) return (170, 200, 210);
        if (c.Contains("halite", StringComparison.Ordinal) || c.Contains("borax", StringComparison.Ordinal)
            || c.Contains("saltpeter", StringComparison.Ordinal) || c.Contains("salt", StringComparison.Ordinal)
            || c.Contains("lime", StringComparison.Ordinal)) return (215, 212, 200);
        if (c.Contains("sulfur", StringComparison.Ordinal)) return (205, 195, 90);
        if (c.Contains("charcoal", StringComparison.Ordinal) || c.Contains("coal", StringComparison.Ordinal)) return (82, 80, 78);

        // Chisel/microblocks: the material is unknown (it lives in the block entity), so we give a neutral "chiselled" tone
        if (c.Contains("chisel", StringComparison.Ordinal) || c.Contains("microblock", StringComparison.Ordinal)
            || c.Contains("carved", StringComparison.Ordinal)) return (152, 144, 126);

        return Fallback(c, id);
    }

    /// <summary>Muted fallback palette: every tone is light enough so that the block does not read as black.</summary>
    private static readonly (byte r, byte g, byte b)[] _Muted =
    {
        (150, 130, 105), (178, 170, 155), (140, 158, 112), (200, 180, 132),
        (162, 132, 108), (134, 142, 112), (178, 180, 170), (170, 152, 126),
        (144, 128, 104), (128, 134, 146), (188, 178, 162), (154, 124, 98),
        (124, 152, 142), (172, 148, 122), (158, 142, 162), (138, 152, 122),
    };

    /// <summary>Stable colour for an unknown code: a hash over the code STRING (mod blocks differ),
    /// mixed with the id. Previously the hash used only the id and some of the tones were nearly black.</summary>
    private static (byte r, byte g, byte b) Fallback(string code, ushort id)
    {
        if (id == 0 && code.Length == 0) return (52, 62, 70);
        uint h = 2166136261u;                       // FNV-1a over the code
        foreach (var ch in code) { h ^= ch; h *= 16777619u; }
        h = unchecked(h * 2654435761u + id);
        return _Muted[h % (uint)_Muted.Length];
    }
}
